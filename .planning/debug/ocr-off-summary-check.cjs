const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const {spawn, execFileSync} = require('node:child_process');
const root = path.resolve(__dirname, '../..');
const run = process.argv[2];
if (!/^[a-z0-9-]+$/.test(run || '')) throw Error('run ID required');
const dir = path.join(__dirname, 'ocr-off-summary-evidence', run);
fs.mkdirSync(dir, {recursive: true});
const output = path.join(dir, 'result.json');
if (fs.existsSync(output) || fs.existsSync(path.join(dir, 'stdout.txt'))) throw Error('preserve existing run');
const baseline = JSON.parse(fs.readFileSync(path.join(__dirname, 'quality-gate-unblock-20261028/baseline.json')));
const inputs = [...new Set([...Object.keys(baseline.inputs), 'pagefolio/ocr_dialog.py', 'tests/test_ocr.py', 'tests/test_ocr_dialog_provider_refresh.py', 'tests/test_release_contract.py', 'pagefolio/constants.py', 'README.md', 'distribution/はじめに.md', '開発履歴.md'])];
const digest = data => crypto.createHash('sha256').update(data).digest('hex');
const hashes = () => Object.fromEntries(inputs.map(p => [p, digest(fs.readFileSync(path.join(root, p)))]));
const before = hashes();
const python = path.join(root, '.venv/Scripts/python.exe');
const args = ['-m', 'pytest', '-q', '-x', '-rA', '-p', 'no:cacheprovider', `--basetemp=${path.join(process.env.LOCALAPPDATA, 'Temp', 'pf-ocr-off-' + run)}`, `--junitxml=${path.join(dir, 'junit.xml')}`];
const started = new Date().toISOString();
fs.writeFileSync(path.join(dir, 'before.json'), JSON.stringify(before, null, 2), {flag:'wx'});
fs.writeFileSync(path.join(dir, 'environment.txt'), execFileSync(python, ['-c', 'import sys,platform; print(sys.version); print(sys.executable); print(platform.platform())'], {cwd:root,windowsHide:true}));
const out = fs.openSync(path.join(dir, 'stdout.txt'), 'wx');
const err = fs.openSync(path.join(dir, 'stderr.txt'), 'wx');
const child = spawn(python, args, {cwd:root, windowsHide:true, stdio:['ignore',out,err], env:{...process.env,PYTHONIOENCODING:'utf-8'}});
child.on('error', e => {console.error(e); process.exitCode=1;});
child.on('close', code => {
  fs.closeSync(out); fs.closeSync(err);
  const after = hashes();
  const changed = inputs.filter(p => before[p] !== after[p]);
  fs.writeFileSync(output, JSON.stringify({started,finished:new Date().toISOString(),argv:[python,...args],code,changed,before,after},null,2), {flag:'wx'});
  console.log(JSON.stringify({code,changed,dir}));
  console.log(fs.readFileSync(path.join(dir, 'stdout.txt'),'utf8').split(/\r?\n/).slice(-5).join('\n'));
  process.exitCode = code || (changed.length ? 1 : 0);
});
